def t(key: str, **fmt) -> str:
    """查当前语言；缺失键回退 zh，再回退键名本身。"""
    text = _STRINGS[_LANG].get(key, _STRINGS["zh"].get(key, key))
    return text.format(**fmt) if fmt else text


def set_lang(lang: str) -> None:
    global _LANG
    if lang in _STRINGS:
        _LANG = lang


def get_lang() -> str:
    return _LANG


def available_langs() -> list[str]:
    return list(_STRINGS)
